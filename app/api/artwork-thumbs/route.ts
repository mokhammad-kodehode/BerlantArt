import { getArtworkThumbs } from "@/lib/artworks";

/**
 * Список работ с миниатюрами для сетки «Все работы» (ArtworkPicker) и
 * счётчика «12 / 204» (ArtworkPosition) — один файл на весь сайт.
 * Страница работы грузит его после отрисовки, браузер держит в кеше.
 *
 * Раньше этот список сидел внутри каждой из ~400 страниц работ и делал
 * каждую в разы тяжелее, а Vercel считает записи в кеш по 8 КБ на
 * страницу (21.10.2026). Теперь одна правка в админке пересобирает один
 * этот файл, а не четыреста его копий.
 *
 * Обновляется вместе со страницами после правки в админке
 * (`artworkThumbsPath` в lib/revalidate.ts), раз в сутки — подстраховка.
 * Значение — литерал: Next читает его при сборке.
 */
export const revalidate = 86400;

export async function GET(): Promise<Response> {
  return Response.json(await getArtworkThumbs());
}
