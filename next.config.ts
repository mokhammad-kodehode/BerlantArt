import type { NextConfig } from "next";

/**
 * Импорт нужен дважды: ради значения и ради побочного эффекта. Схема из
 * lib/env.ts выполняется здесь, при старте dev-сервера и при сборке. Без
 * этого импорта валидация была написана, но не работала — модуль никто
 * не подключал, и сборка с пустым DATABASE_URL прошла бы успешно, а падало
 * бы уже на проде в рантайме.
 */
import { clientEnv } from "./lib/env";

const r2PublicUrl = clientEnv.NEXT_PUBLIC_R2_PUBLIC_URL;

const nextConfig: NextConfig = {
  experimental: {
    /**
     * Корневых layout два — русский и английский (app/(ru), app/(en)/en),
     * и для адреса, не совпавшего ни с одним маршрутом, собрать 404 не из
     * чего. Эту страницу даёт app/global-not-found.tsx (документация Next,
     * not-found.md → global-not-found). Флаг экспериментальный.
     */
    globalNotFound: true,
  },
  images: {
    /**
     * next/image не отдаёт картинки с чужого домена, пока тот не разрешён
     * явно. Домен бакета попадает сюда, только когда он задан: пока
     * хранилище не подключено, картинок оттуда всё равно нет, а пустой
     * шаблон вместо конкретного означал бы разрешение на любой адрес.
     */
    remotePatterns: r2PublicUrl ? [new URL(`${r2PublicUrl.replace(/\/+$/, "")}/**`)] : [],

    /**
     * Сколько разных копий одной картинки может заказать сайт. Каждая новая
     * ширина — отдельная обработка, а их у Vercel на бесплатном тарифе
     * ограниченное число в месяц; кончились — новые копии не создаются,
     * и картинка на сайте пустая (12.10.2026, панель «Все работы»).
     *
     * По умолчанию ширин 15 (8 экранных и 7 мелких). Оставлено 9: 3840 не
     * нужна вовсе — исходники в бакете не шире 2500px (lib/prepare-image.ts),
     * копия шире исходника его не улучшит; соседние 640/750/828 и 1080/1200
     * отличаются на глаз незаметно.
     */
    deviceSizes: [640, 828, 1200, 1920, 2560],
    imageSizes: [64, 128, 256, 384],

    /**
     * Готовая копия хранится 31 день, а не 4 часа по умолчанию: иначе
     * каждые 4 часа каждая картинка обрабатывалась бы заново и снова
     * тратила лимит. Устаревших копий не бывает: у каждого загруженного
     * файла свой ключ с uuid (раздел 2 ARCHITECTURE.md), замена фото —
     * это новый адрес, а не новый файл по старому.
     */
    minimumCacheTTL: 2678400,
  },
};

export default nextConfig;
