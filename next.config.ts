import type { NextConfig } from "next";

/**
 * Импорт нужен дважды: ради значения и ради побочного эффекта. Схема из
 * lib/env.ts выполняется здесь, при старте dev-сервера и при сборке. Без
 * этого импорта валидация была написана, но не работала — модуль никто
 * не подключал, и сборка с пустым DATABASE_URL прошла бы успешно, а падало
 * бы уже на проде в рантайме.
 */
import { clientEnv, serverEnv } from "./lib/env";
import { galleryRedirects } from "./lib/gallery-routes";

const r2PublicUrl = clientEnv.NEXT_PUBLIC_R2_PUBLIC_URL;

/**
 * Копии фото под ширину экрана режет Cloudflare (тикеты О-8, О-9), когда
 * в Vercel задано IMAGE_RESIZE=cloudflare. Пока не задано — заплатка
 * от 12.10.2026: картинки отдаются как есть, без обработки Vercel. На
 * бесплатном тарифе кончился месячный лимит обработки, и новые копии
 * перестали создаваться — на сайте вместо картин было пусто. Исходники
 * в бакете пережаты при загрузке (WebP, до 2500px и до 1 МБ,
 * lib/prepare-image.ts), смотреть можно, но плитка весит как исходник.
 *
 * Как включить — docs/cloudflare-kartinki.md. Сборка с IMAGE_RESIZE и
 * адресом r2.dev падает с объяснением (lib/env.ts): там нарезки нет.
 */
const resize: NextConfig["images"] =
  serverEnv.IMAGE_RESIZE === "cloudflare"
    ? { loader: "custom", loaderFile: "./lib/image-loader.ts" }
    : { unoptimized: true };

/**
 * Защитные заголовки на каждый ответ сайта (тикет О-14, обзор проекта,
 * раздел 7). До 22.10.2026 сайт не отправлял ни одного.
 *
 * - встраивать сайт в чужую страницу нельзя: иначе вход в админку можно
 *   показать внутри чужого сайта и наложить поверх свои поля. Два
 *   заголовка, потому что старые браузеры знают только X-Frame-Options;
 * - тип файла браузер не угадывает, а верит заголовку: файл примерки или
 *   картинку не выдать за скрипт;
 * - чужому сайту по ссылке уходит только адрес нашего, без пути;
 * - камера, микрофон и геолокация внутри страницы выключены — сайт ими не
 *   пользуется. Примерка через камеру открывает программу телефона
 *   (Quick Look, Scene Viewer), а на неё запрет не действует. «Поделиться»
 *   и копирование ссылки (ShareButton) не запрещены.
 *
 * Строгой Content-Security-Policy здесь нет: она отдельный тикет О-15,
 * её надо проверять на видео, примерке и камере. HSTS ставит Vercel.
 */
const securityHeaders = [
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'self'" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  /** Не подсказывать в каждом ответе, на чём сделан сайт. */
  poweredByHeader: false,
  /**
   * Старые адреса галереи с параметрами (`/gallery?category=Цветы`) →
   * готовые страницы категорий и поиск (тикет О-11, lib/gallery-routes.ts).
   */
  async redirects() {
    return galleryRedirects();
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  experimental: {
    /**
     * Корневых layout два — русский и английский (app/(ru), app/(en)/en),
     * и для адреса, не совпавшего ни с одним маршрутом, собрать 404 не из
     * чего. Эту страницу даёт app/global-not-found.tsx (документация Next,
     * not-found.md → global-not-found). Флаг экспериментальный.
     */
    globalNotFound: true,
  },
  images: {
    ...resize,
    /**
     * next/image не отдаёт картинки с чужого домена, пока тот не разрешён
     * явно. Домен бакета попадает сюда, только когда он задан: пока
     * хранилище не подключено, картинок оттуда всё равно нет, а пустой
     * шаблон вместо конкретного означал бы разрешение на любой адрес.
     */
    remotePatterns: r2PublicUrl ? [new URL(`${r2PublicUrl.replace(/\/+$/, "")}/**`)] : [],

    /**
     * Сколько разных копий одной картинки может заказать сайт. Каждая новая
     * ширина — отдельная обработка, а их на бесплатных тарифах ограниченное
     * число в месяц. У Vercel кончились — новые копии не создаются, и
     * картинка на сайте пустая (12.10.2026, панель «Все работы»). У
     * Cloudflare их 5000 в месяц: 9 ширин на ~250 фото — не больше 2250,
     * а сверх лимита браузер получит исходник (lib/image-resize.ts).
     *
     * По умолчанию ширин 15 (8 экранных и 7 мелких). Оставлено 9: 3840 не
     * нужна вовсе — исходники в бакете не шире 2500px (lib/prepare-image.ts),
     * копия шире исходника его не улучшит; соседние 640/750/828 и 1080/1200
     * отличаются на глаз незаметно.
     */
    deviceSizes: [640, 828, 1200, 1920, 2560],
    imageSizes: [64, 128, 256, 384],

    /**
     * Только для обработки Vercel, Cloudflare хранит копии сам.
     * Готовая копия хранится 31 день, а не 4 часа по умолчанию: иначе
     * каждые 4 часа каждая картинка обрабатывалась бы заново и снова
     * тратила лимит. Устаревших копий не бывает: у каждого загруженного
     * файла свой ключ с uuid (раздел 2 ARCHITECTURE.md), замена фото —
     * это новый адрес, а не новый файл по старому.
     */
    minimumCacheTTL: 2678400,
  },
};

export default nextConfig;
