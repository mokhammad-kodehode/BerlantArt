-- Перевод работ на список категорий, размеров и техники из формы (Э6-6).
--
-- Схема не меняется — только данные. Категория в базе осталась строкой,
-- список живёт в lib/artwork-form.ts. Без этой миграции старые значения
-- остались бы в фильтре галереи рядом с новыми, а форма не дала бы
-- сохранить работу, не сменив категорию.
--
-- Соответствия утверждены заказчиком 19 сентября 2026. «Горный пейзаж»
-- стоял у одной работы — «Башни в тумане», поэтому он переходит в «Башни»,
-- а не в «Горы». Значение, которого здесь нет, не трогается: форма покажет
-- его с пометкой «нет в списке» и попросит выбрать.

UPDATE "Artwork" SET "category" = 'Башни' WHERE "category" = 'Горный пейзаж';
UPDATE "Artwork" SET "category" = 'Поле и дорога' WHERE "category" = 'Полевой пейзаж';
UPDATE "Artwork" SET "category" = 'Село' WHERE "category" = 'Сельский мотив';
UPDATE "Artwork" SET "category" = 'Старая архитектура' WHERE "category" = 'Арх';

-- Та же техника, записанная в другом порядке, и размер без пробелов
-- и единиц: приводятся к виду, который теперь ставит форма.
UPDATE "Artwork" SET "technique" = 'Холст, масло' WHERE "technique" = 'масло, холст';
UPDATE "Artwork" SET "dimensions" = '60 × 80 см' WHERE "dimensions" = '60x80';
