import { cn } from "@/lib/cn";

/**
 * Стрелка в ссылке или кнопке. Когда на ссылку наводят мышь или ставят
 * фокус, стрелка подаётся в свою сторону — подсказка «туда», а не
 * украшение (globals.css, .arrow). Так была сделана стрелка у «О
 * художнице» в hero; с 23.10.2026 — у всех стрелок сайта (заказчик).
 *
 * Поэтому стрелок нет в строках словарей: внутри текста её не сдвинуть.
 * Скринридеру стрелка не читается — направление уже сказано словами.
 */
export function Arrow({ dir = "next" }: { dir?: "next" | "back" }) {
  return (
    <span aria-hidden="true" className={cn("arrow", dir === "back" && "arrow-back")}>
      {dir === "back" ? "←" : "→"}
    </span>
  );
}
