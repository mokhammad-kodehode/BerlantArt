import type { ImageLoaderProps } from "next/image";

/**
 * Копии фото под ширину экрана от Cloudflare Images (тикеты О-8, О-9).
 *
 * Сайт просит у Cloudflare копию фото под ширину экрана: плитке в галерее —
 * 640px вместо исходника до 2500px и до 1 МБ. Cloudflare режет её при
 * первом запросе и дальше отдаёт из своего кеша; в бакете ничего нового
 * не появляется, старые фото работают сразу, без нарезки задним числом.
 * Свои копии при загрузке (И-1) уже пробовали — 13.10.2026 на проде упала
 * загрузка фото, причину не нашли (TICKETS-images.md).
 *
 * Работает, только когда задан IMAGE_RESIZE=cloudflare (next.config.ts
 * подключает тогда lib/image-loader.ts). Без него картинки отдаются как
 * есть, и этот код не участвует вовсе.
 *
 * Модуль общий для браузера и сервера: адрес копии строит next/image в
 * браузере, а isResizable нужна ещё и проверке настройки в lib/env.ts.
 * Поэтому сам он lib/env.ts не импортирует — проверка серверных
 * переменных в браузере упала бы.
 */

/**
 * Качество копии. 85 — значение Cloudflare по умолчанию, у Next — 75.
 * Замер на фото картин, ширина 640px: 75 — 22–54 КБ, 85 — 40–87 КБ. Взято
 * 85: на этом сайте разглядывают мазок, и даже так плитка весит до 87 КБ
 * против нынешнего исходника до 1 МБ. Одно значение на весь
 * сайт намеренно: фон-размытие на странице работы — та же картина, и при
 * разном качестве браузер скачал бы её дважды.
 */
const defaultQuality = 85;

/**
 * Можно ли просить у Cloudflare копию этой картинки.
 *
 * Нет — у картинок из public/ (путь от корня, «/about/…»): их отдаёт
 * Vercel, а не бакет, и они уже пережаты под свой размер. Нет — у адресов
 * r2.dev: у этого домена нет /cdn-cgi/image/, копия вернулась бы ошибкой.
 * Такой адрес может прийти из страницы, открытой или закешированной до
 * переезда на свой домен, — пусть покажет исходник, а не пустое место.
 *
 * Для картинок из public/ Next в режиме разработки пишет в консоль, что
 * загрузчик «не учитывает ширину». Так и задумано; на собранном сайте
 * этого предупреждения нет.
 */
export function isResizable(src: string): boolean {
  if (src.startsWith("/")) return false;
  return !new URL(src).hostname.endsWith(".r2.dev");
}

/**
 * Адрес копии: `<домен картинок>/cdn-cgi/image/<параметры>/<путь в бакете>`.
 *
 * - `format=auto` — AVIF или WebP, что поддерживает браузер; Cloudflare
 *   считает это одной копией, а не двумя;
 * - `fit=scale-down` — не увеличивать: копия шире исходника лучше
 *   не станет, только тяжелее (экран 2560px, фото 2500px);
 * - `onerror=redirect` — если Cloudflare копию сделать не смог (кончился
 *   бесплатный лимит в 5000 копий за месяц, сбой), браузер получает
 *   исходник. Работает, потому что фото лежит на том же домене, что и
 *   нарезка.
 */
export function cloudflareImageUrl({ src, width, quality }: ImageLoaderProps): string {
  if (!isResizable(src)) return src;

  const url = new URL(src);
  const options = [
    `width=${width}`,
    `quality=${quality ?? defaultQuality}`,
    "format=auto",
    "fit=scale-down",
    "onerror=redirect",
  ].join(",");

  return `${url.origin}/cdn-cgi/image/${options}${url.pathname}${url.search}`;
}
