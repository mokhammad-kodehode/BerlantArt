/**
 * Раскладка стены работ — развеска (главная и галерея) — и её порции.
 *
 * До 23.10.2026 в галерее была плотная сетка коллажа: блоки по пять
 * плиток, крупные ячейки 2×2, тест на дыры. Она обрезала картины под
 * ячейки, и заказчик заменил её развеской — как на главной. Код сетки
 * удалён, он есть в истории git.
 */

/** Плитка стены: пометка для CSS и реальная ширина отрисовки для `sizes`. */
export type CollageTile = {
  className: string;
  sizes: string;
};

/**
 * Развеска (заказчик, 23.10.2026, вариант Д): картины целиком,
 * в своих пропорциях, разного размера и центром на одной линии — как на
 * стене в зале. Порядок — как пришёл, ни дыр, ни ячеек: размер и место
 * задаёт CSS (globals.css, .wall-hang), здесь только пометка крупной работы
 * и `sizes`. Крупная (`isLarge` в админке) — самая большая в развеске.
 *
 * `sizes` — с запасом по самой широкой: крупная горизонтальная на
 * компьютере занимает до ~40% ширины, на телефоне в паре — до половины.
 */
export function hangLayout<T extends { isLarge: boolean }>(
  items: readonly T[],
): (CollageTile & { item: T })[] {
  return items.map((item) => ({
    item,
    className: item.isLarge ? "wall-hang-large" : "",
    sizes: "(max-width: 767px) 50vw, 40vw",
  }));
}

/**
 * Сколько плиток стена рисует сразу и сколько добавляет за раз (тикет
 * О-11). Раньше рисовались все: на 203 работах страница галереи весила
 * 760 КБ, и телефон долго её разбирал.
 *
 * Стык порций развеску не сбивает: размеры чередуются по номеру плитки
 * в общем списке (nth-child), а следующая порция дописывается в тот же
 * список, и плитки не переезжают.
 */
export const revealStep = 40;

/**
 * Сколько плиток показать, чтобы на стене была плитка с номером `index`
 * (с нуля): целыми порциями, но не больше, чем есть. Нужно возврату со
 * страницы работы к её плитке, если она дальше первой порции.
 */
export function revealCountFor(index: number, total: number, step = revealStep): number {
  return Math.min(total, (Math.floor(index / step) + 1) * step);
}
